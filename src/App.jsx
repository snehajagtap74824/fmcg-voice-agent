import { History, Info, MessageSquarePlus } from 'lucide-react'
import { useEffect, useState } from 'react'
import { getRetailers } from './api.js'
import ConversationScreen from './components/ConversationScreen.jsx'
import HistoryList from './components/HistoryList.jsx'
import Logo from './components/Logo.jsx'
import './App.css'

// The prototype runs as a single retailer profile: Shree Ganesh Kirana Store, Pune (server/data/retailers.json).
const RETAILER_ID = 'R001'

const NAV = [
  { id: 'conversation', label: 'New Conversation', Icon: MessageSquarePlus },
  { id: 'history', label: 'Conversation History', Icon: History },
]

function initials(name = '') {
  return name
    .split(/\s+/)
    .filter(Boolean)
    .slice(0, 2)
    .map((word) => word[0].toUpperCase())
    .join('')
}

export default function App() {
  const [tab, setTab] = useState('conversation')
  const [retailer, setRetailer] = useState(null)

  // Header chip only; the conversation gets its own retailer record from /conversations/start.
  useEffect(() => {
    getRetailers()
      .then((list) => setRetailer(list.find((r) => r.id === RETAILER_ID) ?? null))
      .catch(() => setRetailer(null))
  }, [])

  return (
    <div className="app">
      <header className="topbar">
        <div className="brand">
          <Logo />
          <div>
            <h1>Retailer Assistant</h1>
            <p className="brand__tagline">Your AI partner for product information, schemes and enquiries</p>
          </div>
          <span className="pill pill--demo">Demo Mode</span>
        </div>
        {retailer && (
          <div className="retailer-chip">
            <span className="avatar avatar--initials">{initials(retailer.ownerName)}</span>
            <div>
              <strong>{retailer.name}</strong>
              <span>Retailer</span>
            </div>
          </div>
        )}
      </header>

      <div className="shell">
        <nav className="sidebar" aria-label="Main">
          <ul className="nav">
            {NAV.map(({ id, label, Icon }) => (
              <li key={id}>
                <button
                  type="button"
                  className={`nav__item${tab === id ? ' nav__item--active' : ''}`}
                  aria-current={tab === id ? 'page' : undefined}
                  onClick={() => setTab(id)}
                >
                  <Icon size={18} aria-hidden="true" />
                  {label}
                </button>
              </li>
            ))}
          </ul>
          <div className="card about">
            <h3>
              <Info size={16} aria-hidden="true" /> About this demo
            </h3>
            <p>
              A prototype AI voice assistant for retailers. All products, prices, schemes and retailers are fictional,
              and answers are generated by AI from sample data.
            </p>
          </div>
        </nav>

        <main className="main">
          {/* Kept mounted while hidden so switching views never loses a conversation in progress. */}
          <div className="view" hidden={tab !== 'conversation'}>
            <ConversationScreen retailerId={RETAILER_ID} />
          </div>
          {/* Mounted on each visit so the list is re-fetched and shows the latest saved call. */}
          {tab === 'history' && <HistoryList />}
        </main>
      </div>
    </div>
  )
}
